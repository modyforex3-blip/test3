// Supported publishing interval durations in milliseconds
const FREQUENCY_INTERVALS_MS = {
  every_hour: 60 * 60 * 1000,
  every_6_hours: 6 * 60 * 60 * 1000,
  twice_daily: 12 * 60 * 60 * 1000,
  daily: 24 * 60 * 60 * 1000,
  every_3_days: 3 * 24 * 60 * 60 * 1000,
  weekly: 7 * 24 * 60 * 60 * 1000
};

// Generator function
function generateNewArticle(customCategory = null) {
  const db = getDB();
  if (!db.articles) db.articles = [];

  let available = articleTemplates;
  if (customCategory && customCategory !== 'all') {
    const matched = articleTemplates.filter(t => t.category === customCategory);
    if (matched.length > 0) available = matched;
  } else if (db.aiBlogger && Array.isArray(db.aiBlogger.allowedCategories) && db.aiBlogger.allowedCategories.length > 0) {
    const matched = articleTemplates.filter(t => db.aiBlogger.allowedCategories.includes(t.category));
    if (matched.length > 0) available = matched;
  }

  // Prefer templates not recently published
  const recentTitles = new Set(db.articles.slice(0, 3).map(a => a.titleAr));
  const freshPool = available.filter(t => !recentTitles.has(t.titleAr));
  const pool = freshPool.length > 0 ? freshPool : available;

  const template = pool[Math.floor(Math.random() * pool.length)];
  const timestamp = Date.now();

  const variations = [
    "دراسة تحليلية معمقة من فريق التحرير التقني في منصة مليونير.",
    "رؤية استراتيجية متكاملة لرواد الأعمال وصناع القرار الرقمي.",
    "دليل عملي موثق بأحدث المعايير والأساليب التقنية الحديثة."
  ];
  const variation = variations[Math.floor(Math.random() * variations.length)];

  const newArticle = {
    id: 'art-' + timestamp,
    titleAr: template.titleAr,
    titleEn: template.titleEn,
    category: template.category,
    categoryNameAr: template.categoryNameAr,
    image: template.image,
    readTime: template.readTime,
    publishedAt: new Date().toISOString(),
    author: "روبوت الذكاء الاصطناعي • منصة مليونير",
    excerpt: template.excerpt + " " + variation,
    content: template.content,
    viewsCount: Math.floor(Math.random() * 800) + 450
  };

  db.articles.unshift(newArticle);
  if (!db.aiBlogger) db.aiBlogger = {};
  db.aiBlogger.lastRun = new Date().toISOString();

  saveDB(db);
  console.log(`🤖 [AI Blogger] تم توليد ونشر مقال احترافي طويل بنجاح: "${newArticle.titleAr}"`);
  return newArticle;
}

// Scheduled Auto-Blogger Check honoring configured interval
function checkAndRunScheduledDailyBlogger() {
  const db = getDB();
  const config = db.aiBlogger || { enabled: true, frequency: "daily" };

  if (config.enabled === false || config.frequency === 'manual') return;

  const lastRun = config.lastRun ? new Date(config.lastRun).getTime() : 0;
  const now = Date.now();
  const intervalMs = FREQUENCY_INTERVALS_MS[config.frequency] || FREQUENCY_INTERVALS_MS.daily;

  if (now - lastRun >= intervalMs) {
    console.log(`⏰ [AI Blogger] حان موعد النشر المجدول (${config.frequency || 'daily'})، جاري التوليد...`);
    generateNewArticle();
  }
}

// Check every 15 minutes so hourly / 6-hour / 12-hour / daily / weekly schedules fire accurately
function initAIBloggerScheduler() {
  setTimeout(() => {
    checkAndRunScheduledDailyBlogger();
  }, 5000);

  setInterval(() => {
    checkAndRunScheduledDailyBlogger();
  }, 15 * 60 * 1000);
}

